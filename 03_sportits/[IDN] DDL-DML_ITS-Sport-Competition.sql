    id varchar(36) NOT NULL,
    nama varchar(256) NOT NULL,
    nrp char(10) NOT NULL,
    no_telepon varchar(15) NOT NULL,
    divisi varchar(256) NOT NULL,
    jadwal_kompetisi_id varchar(36) NULL,
