    id varchar(36) NOT NULL,
    waktu_mulai timestamp NOT NULL,
    waktu_akhir timestamp NOT NULL,
    lokasi varchar(256) NOT NULL,
    nama_tim_1 varchar(256) NOT NULL,
    nama_tim_2 varchar(256) NOT NULL,
    CONSTRAINT pk_jadwal_kompetisi PRIMARY KEY (id)
);

-- Table: panitia
